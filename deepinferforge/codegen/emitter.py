# -*- coding: utf-8 -*-
"""Render a KernelSpec as source text for a target backend.

The emitted text is illustrative-but-real: correct signatures, grid/block
mapping and the inner loop shape a hand-written kernel would have. In a
production compiler this is where backend-specific intrinsics, vectorization
and shared-memory tiling would be inserted.
"""


def _signature_cuda(kernel):
    return "extern \"C\" __global__ void %s(const float* __restrict__ A,\n                                     float* __restrict__ C, int N)" % kernel.name


def _signature_cann(kernel):
    return "__global__ __aicore__ void %s(GM_ADDR A, GM_ADDR C, int64_t N)" % kernel.name


def emit_cuda(kernel):
    cfg = kernel.config or {}
    tile = cfg.get("tile", 32)
    lines = [
        "// generated by deepinferforge (NVIDIA / CUDA backend)",
        _signature_cuda(kernel),
        "{",
        "  int tid = blockIdx.x * blockDim.x + threadIdx.x;",
        "  if (tid >= N) return;",
        "  // tiled accumulation over the reduction axis (tile=%d)" % tile,
        "  float acc = 0.0f;",
        "  #pragma unroll",
        "  for (int j = 0; j < %d; ++j) { acc += A[tid * %d + j]; }" % (tile, tile),
        "  C[tid] = acc;",
        "}",
    ]
    return "\n".join(lines)


def emit_cann(kernel):
    cfg = kernel.config or {}
    tile = cfg.get("tile", 32)
    lines = [
        "// generated by deepinferforge (Ascend / CANN backend)",
        _signature_cann(kernel),
        "{",
        "  int64_t tid = block_idx * block_dim + thread_idx;",
        "  if (tid >= N) return;",
        "  // vectorized load into unified buffer (tile=%d)" % tile,
        "  float acc = 0.0f;",
        "  for (int64_t j = 0; j < %d; ++j) { acc += *(float*)(A + tid * %d + j); }" % (tile, tile),
        "  *(float*)(C + tid) = acc;",
        "}",
    ]
    return "\n".join(lines)


def emit_source(kernel):
    """Pick the emitter for the kernel's backend."""
    if kernel.backend == "ascend":
        return emit_cann(kernel)
    return emit_cuda(kernel)
